export function getDirForLang(lang: AppLanguage): 'rtl' | 'ltr' {
  return lang === 'ar' ? 'rtl' : 'ltr';
}

/**
 * Strips any legacy bilingual parentheses like "واتساب (WhatsApp)" -> "واتساب"
 * so service/country names always appear strictly in ONE language.
 */
function stripBilingualParens(raw: string): string {
  return String(raw || '')
    .replace(/\s*\([^)]*[A-Za-z][^)]*\)\s*/g, '')
    .trim();
}

export function getLocalizedServiceName(
  service: Pick<GrizzlyServiceItem, 'code' | 'nameAr' | 'nameEn' | 'nameTr'>,
  lang: AppLanguage
): string {
  if (lang === 'ar') {
    const clean = stripBilingualParens(service.nameAr || service.nameEn || service.code);
    return clean || service.nameEn || service.code.toUpperCase();
  }
  if (lang === 'tr') {
    return (service.nameTr || service.nameEn || service.code).trim();
  }
  return (service.nameEn || service.nameTr || service.code).trim();
}

export function getLocalizedCountryName(
  country: Pick<GrizzlyCountry, 'id' | 'nameAr' | 'nameEn' | 'nameTr'>,
  lang: AppLanguage
): string {
  if (lang === 'ar') {
    const clean = stripBilingualParens(country.nameAr || country.nameEn || country.id);
    return clean || country.nameEn || country.id;
  }
  if (lang === 'tr') {
    return (country.nameTr || country.nameEn || country.nameAr || country.id).trim();
  }
  return (country.nameEn || country.nameTr || country.nameAr || country.id).trim();
}

